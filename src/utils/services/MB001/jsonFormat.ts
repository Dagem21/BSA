export const MB001Format = (
    returnKey: string = "MB001MB001",
    instCode: string = "0000001",
    finYear: number = 2026,
    startDate: string,
    endDate: string,
    valuesMap: Record<string, string> = {}
) => {
    const fmt = (val: string | number | undefined | null) => {
        if (val !== undefined && val !== null) {
            const str = val.toString().trim();
            if (
                str !== "" &&
                str !== "-" &&
                str !== "—" &&
                str !== "–" &&
                str !== "--" &&
                str.toLowerCase() !== "n/a" &&
                str.toLowerCase() !== "nil"
            ) {
                return str;
            }
        }
        return "0";
    };

    const returnItems = MB001_DESCRIPTIONS.map((item) => ({
        Code: item.code,
        Value: fmt(valuesMap[item.code]),
        _description: item.desc,
        _dataType: "NUMERIC",
        _required: false
    }));

    return {
        ReturnKey: returnKey,
        InstCode: instCode,
        FinYear: finYear,
        StartDate: startDate,
        EndDate: endDate,
        ReturnItemsList: returnItems,
        DynamicItemsList: []
    };
};

